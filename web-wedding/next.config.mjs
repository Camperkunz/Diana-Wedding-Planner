/** @type {import('next').NextConfig} */
import { fileURLToPath } from 'node:url';
import { initOpenNextCloudflareForDev } from '@opennextjs/cloudflare';

// ── Security headers ────────────────────────────────────────────────────────
// Sent with every response. None of them change how the site looks or renders;
// they remove whole classes of browser-level attacks:
//  - nosniff            : the browser must never guess a MIME type,
//  - DENY               : the site can never be put inside a frame (clickjacking),
//  - Referrer-Policy    : full URLs are not sent to other origins,
//  - Permissions-Policy : camera / mic / location / payment stay off (unused),
//  - HSTS               : browsers only ever talk to this domain over HTTPS,
//  - COOP               : no other window can reach into this one,
//  - CSP                : only the scripts, images and frames the site really uses.
//
// The Content-Security-Policy is an allow-list for exactly what this website
// loads: the Sanity image CDN (all photos), the YouTube / Vimeo players used by
// the Backstage page plus their thumbnails, and Google Analytics (which only
// becomes active when a Measurement ID is saved in the Studio).
// `'unsafe-inline'` is required by the small inline snippets Next.js and the
// GA4 tag emit; `'unsafe-eval'` is added in development only (Turbopack).
//
// NOTE: headers() only applies to responses generated by the Worker. Files under
// /_next/static are served straight from Cloudflare's asset server, which is why
// their cache header lives in public/_headers instead.

const nextConfig = (phase) => {
  // The phase is passed by the Next.js CLI itself. Checking NODE_ENV here is
  // unreliable: on Next 16 the config is evaluated before NODE_ENV is pinned to
  // "production", which used to leak 'unsafe-eval' into the live CSP.
  const isDev = phase === 'phase-development-server';

  const csp = [
    "default-src 'self'",
    "base-uri 'self'",
    "object-src 'none'",
    "frame-ancestors 'none'",
    "form-action 'self'",
    `script-src 'self' 'unsafe-inline'${isDev ? " 'unsafe-eval'" : ''} https://www.googletagmanager.com https://www.google-analytics.com https://challenges.cloudflare.com`,
    "script-src-attr 'none'",
    "style-src 'self' 'unsafe-inline'",
    "img-src 'self' data: blob: https://cdn.sanity.io https://img.youtube.com https://i.ytimg.com https://i.vimeocdn.com",
    "font-src 'self'",
    "connect-src 'self' https://cdn.sanity.io https://*.sanity.io https://*.google-analytics.com https://www.googletagmanager.com https://challenges.cloudflare.com",
    "frame-src https://www.youtube.com https://www.youtube-nocookie.com https://player.vimeo.com https://challenges.cloudflare.com",
    "media-src 'self'",
    "worker-src 'self' blob:",
    "manifest-src 'self'",
  ].join('; ');

  const securityHeaders = [
    { key: 'X-Content-Type-Options', value: 'nosniff' },
    { key: 'X-Frame-Options', value: 'DENY' },
    { key: 'Referrer-Policy', value: 'strict-origin-when-cross-origin' },
    { key: 'Permissions-Policy', value: 'camera=(), microphone=(), geolocation=(), payment=(), usb=()' },
    { key: 'Strict-Transport-Security', value: 'max-age=63072000; includeSubDomains; preload' },
    { key: 'Cross-Origin-Opener-Policy', value: 'same-origin' },
    { key: 'Content-Security-Policy', value: csp },
  ];

  return {
    // Do not advertise the framework/version in responses.
    poweredByHeader: false,
    // ── www → apex ──────────────────────────────────────────────────────────
    // `www.dianavoloshina.com` is a Cloudflare custom domain on the same Worker,
    // so without this rule the whole site answered 200 on both hosts and search
    // engines saw two copies of every page. The redirect is permanent (308,
    // `permanent: true`) and path-preserving.
    //
    // Cheaper alternative: a Cloudflare Redirect Rule (Rules → Redirect Rules).
    // It terminates the request at the edge, so `www` traffic never reaches the
    // Worker and costs no invocations — the rule below exists as the default
    // that works without touching the dashboard.
    async redirects() {
      return [
        {
          source: '/:path*',
          has: [{ type: 'host', value: 'www.dianavoloshina.com' }],
          destination: 'https://dianavoloshina.com/:path*',
          permanent: true,
        },
      ];
    },
    async headers() {
      return [{ source: '/:path*', headers: securityHeaders }];
    },
  };
};

export default nextConfig;

// Lets `next dev` see the Cloudflare bindings (and the .env files, the same way
// the deployed Worker does). The @opennextjs/cloudflare adapter is ESM-only,
// which is the reason this config lives in a .mjs file.
//
// A dedicated config file is passed instead of `wrangler.jsonc` because the dev
// platform is wrangler's `getPlatformProxy`, which starts Miniflare with an
// EMPTY worker script: it never loads `main`, so nothing exports the
// `DOQueueHandler` Durable Object and workerd warns on every dev start that
// NEXT_CACHE_DO_QUEUE references a class that does not exist (a future workerd
// release may even turn that into a startup error). `next dev` renders every
// request on demand, so it never queues an ISR revalidation and does not need
// Durable Objects at all. `wrangler.dev.jsonc` therefore mirrors the non-DO
// parts of `wrangler.jsonc` — keep the two in sync if you add bindings or
// `vars` that the app reads at runtime. Deployments, `preview` and
// `wrangler dev` keep using `wrangler.jsonc` (with the DO queue).
initOpenNextCloudflareForDev({
  configPath: fileURLToPath(new URL('./wrangler.dev.jsonc', import.meta.url)),
});
